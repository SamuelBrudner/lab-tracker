import { createHash } from "node:crypto";
import { readFile, rm, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { build, context } from "esbuild";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const frontendDir = resolve(repoRoot, "src/lab_tracker/frontend");
const watchMode = process.argv.includes("--watch");
// Watch (and an explicit --dev) build for development: unminified, source-mapped,
// and NODE_ENV=development so React's dev warnings/invariants fire. The default
// production build is untouched, so its committed output stays byte-identical.
const devMode = watchMode || process.argv.includes("--dev");

function normalizeTextAssetBytes(buffer) {
  return Buffer.from(buffer.toString("utf8").replace(/\r\n/g, "\n"), "utf8");
}

async function staticAssetVersion() {
  const hash = createHash("sha256");
  for (const filename of ["app.js", "styles.css"]) {
    hash.update(filename);
    hash.update("\0");
    hash.update(
      normalizeTextAssetBytes(await readFile(resolve(frontendDir, filename)))
    );
    hash.update("\0");
  }
  return hash.digest("hex").slice(0, 12);
}

async function stampShellAssetVersion(version) {
  const indexPath = resolve(frontendDir, "index.html");
  const swPath = resolve(frontendDir, "sw.js");
  const [indexHtml, serviceWorker] = await Promise.all([
    readFile(indexPath, "utf8"),
    readFile(swPath, "utf8"),
  ]);
  await Promise.all([
    writeFile(
      indexPath,
      indexHtml.replace(
        /\/app\/static\/(app\.js|styles\.css)\?v=[^"']+/g,
        (match, asset) => `/app/static/${asset}?v=${version}`
      ),
      "utf8"
    ),
    writeFile(
      swPath,
      serviceWorker
        .replace(
          /const CACHE_VERSION = "v[^"]+";/,
          `const CACHE_VERSION = "v-${version}";`
        )
        .replace(
          /\/app\/static\/(app\.js|styles\.css)\?v=[^"']+/g,
          (match, asset) => `/app/static/${asset}?v=${version}`
        ),
      "utf8"
    ),
  ]);
}

function stampShellAssetsPlugin() {
  return {
    name: "stamp-shell-assets",
    setup(buildContext) {
      buildContext.onEnd(async (result) => {
        if (result.errors.length > 0) {
          return;
        }
        if (devMode) {
          // Keep the emitted app.js.map and do NOT re-stamp the committed
          // index.html/sw.js, so a dev/watch build never strips source maps or
          // dirties tracked shell files.
          console.log("rebuilt frontend bundle (dev: unminified + source map)");
          return;
        }
        await rm(resolve(frontendDir, "app.js.map"), { force: true });
        const version = await staticAssetVersion();
        await stampShellAssetVersion(version);
      });
    },
  };
}

const buildOptions = {
  absWorkingDir: repoRoot,
  entryPoints: ["././src/lab_tracker/frontend_src/app.jsx"],
  outfile: resolve(frontendDir, "app.js"),
  bundle: true,
  minify: !devMode,
  sourcemap: devMode ? "linked" : false,
  format: "iife",
  platform: "browser",
  define: {
    "process.env.NODE_ENV": devMode ? "\"development\"" : "\"production\"",
  },
  banner: {
    js: devMode
      ? "/* dev build — npm run dev:frontend (not for commit) */"
      : "/* generated by `npm run build:frontend` */",
  },
  plugins: [stampShellAssetsPlugin()],
};

if (watchMode) {
  const buildContext = await context(buildOptions);
  await buildContext.watch();
  console.log("watching frontend sources...");
} else {
  await build(buildOptions);
}
